use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use muu_dict::CoarsePos;

#[derive(Clone, Debug)]
struct Context {
    id: u16,
    coarse: &'static str,
}

#[derive(Clone, Debug)]
struct ConjugationForm {
    name: String,
    surface_suffix: String,
    reading_suffix: String,
}

#[derive(Clone, Debug)]
struct GeneratedForm {
    surface_suffix: String,
    reading_suffix: String,
    context: Context,
}

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let repo = manifest.join("../..");
    let rules = repo.join("third_party/mozc-oss/src/data/rules");
    let id_path = repo.join("third_party/mozc-oss/src/data/dictionary_oss/id.def");
    let user_pos_path = rules.join("user_pos.def");
    let cforms_path = rules.join("cforms.def");
    let special_pos_path = rules.join("special_pos.def");

    for path in [&id_path, &user_pos_path, &cforms_path, &special_pos_path] {
        println!("cargo:rerun-if-changed={}", path.display());
    }

    let contexts = parse_contexts(&id_path);
    assert_eq!(contexts.len(), 2672, "production id.def axis changed");
    let conjugations = parse_conjugations(&cforms_path);
    let special = parse_special_pos(&special_pos_path);
    assert_eq!(
        special,
        ["特殊,郵便番号", "特殊,短縮よみ", "特殊,サジェストのみ"],
        "special POS order is an ABI-like dictionary authority"
    );

    let generated = generate_user_pos(&user_pos_path, &contexts, &conjugations);
    fs::write(
        PathBuf::from(env::var_os("OUT_DIR").unwrap()).join("user_pos_generated.rs"),
        generated,
    )
    .unwrap();
}

fn data_lines(path: &Path) -> Vec<String> {
    fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("failed to read {}: {error}", path.display()))
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(str::to_owned)
        .collect()
}

fn parse_contexts(path: &Path) -> BTreeMap<String, Context> {
    let mut result = BTreeMap::new();
    for line in data_lines(path) {
        let (id, feature) = line
            .split_once(' ')
            .unwrap_or_else(|| panic!("invalid id.def line: {line}"));
        let id = id.parse::<u16>().unwrap();
        let major = feature.split(',').next().unwrap();
        let context = Context {
            id,
            coarse: CoarsePos::from_mozc_major(major)
                .unwrap_or_else(|| panic!("unknown coarse POS: {major}"))
                .rust_variant_name(),
        };
        assert!(result.insert(feature.to_owned(), context).is_none());
    }
    result
}

fn parse_conjugations(path: &Path) -> BTreeMap<String, Vec<ConjugationForm>> {
    let mut result: BTreeMap<String, Vec<ConjugationForm>> = BTreeMap::new();
    for line in data_lines(path) {
        let fields: Vec<&str> = line.split('\t').collect();
        assert_eq!(fields.len(), 5, "invalid cforms.def line: {line}");
        result
            .entry(fields[0].to_owned())
            .or_default()
            .push(ConjugationForm {
                name: fields[1].to_owned(),
                surface_suffix: star_to_empty(fields[2]).to_owned(),
                reading_suffix: star_to_empty(fields[3]).to_owned(),
            });
    }
    result
}

fn parse_special_pos(path: &Path) -> Vec<String> {
    data_lines(path)
}

fn generate_user_pos(
    path: &Path,
    contexts: &BTreeMap<String, Context>,
    conjugations: &BTreeMap<String, Vec<ConjugationForm>>,
) -> String {
    let lines = data_lines(path);
    assert_eq!(lines.len(), 45, "user_pos.def POS count changed");
    let mut output =
        String::from("// @generated by build.rs from the pinned Mozc rules. Do not edit.\n\n");
    let mut definitions = Vec::new();
    let mut ids = BTreeSet::new();
    let mut runtime_rows = 0usize;

    for line in lines {
        let fields: Vec<&str> = line.split('\t').collect();
        assert_eq!(fields.len(), 5, "invalid user_pos.def line: {line}");
        let [_label, id, conjugation, feature, cost] = <[&str; 5]>::try_from(fields).unwrap();
        assert!(ids.insert(id.to_owned()), "duplicate user POS id: {id}");
        let cost = cost.parse::<i32>().unwrap();

        let (behavior, forms, base_surface_suffix, base_reading_suffix) = match id {
            "SUPPRESSION_WORD" => ("Suppression", Vec::new(), "", ""),
            "SUGGESTION_ONLY" => ("DormantSuggestion", Vec::new(), "", ""),
            "ABBREVIATION" => (
                "Abbreviation",
                vec![GeneratedForm {
                    surface_suffix: String::new(),
                    reading_suffix: String::new(),
                    context: Context {
                        id: 2673,
                        coarse: CoarsePos::Other.rust_variant_name(),
                    },
                }],
                "",
                "",
            ),
            _ if conjugation == "*" => {
                let resolved_feature = normalized_feature(feature);
                let context = resolve_context(contexts, &resolved_feature).unwrap_or_else(|| {
                    panic!("unresolved user POS feature {id}: {resolved_feature}")
                });
                (
                    "Runtime",
                    vec![GeneratedForm {
                        surface_suffix: String::new(),
                        reading_suffix: String::new(),
                        context,
                    }],
                    "",
                    "",
                )
            }
            _ => {
                let cforms = conjugations
                    .get(conjugation)
                    .unwrap_or_else(|| panic!("missing conjugation family: {conjugation}"));
                let base = cforms
                    .iter()
                    .find(|form| form.name == "基本形")
                    .unwrap_or_else(|| panic!("missing base form: {conjugation}"));
                let forms = cforms
                    .iter()
                    .map(|form| {
                        let resolved_feature =
                            normalized_feature(&feature.replace("<cform>", &form.name));
                        GeneratedForm {
                            surface_suffix: form.surface_suffix.clone(),
                            reading_suffix: form.reading_suffix.clone(),
                            context: resolve_context(contexts, &resolved_feature).unwrap_or_else(
                                || panic!("unresolved expanded feature {id}: {resolved_feature}"),
                            ),
                        }
                    })
                    .collect();
                (
                    "Runtime",
                    forms,
                    base.surface_suffix.as_str(),
                    base.reading_suffix.as_str(),
                )
            }
        };

        runtime_rows += forms.len();
        definitions.push((
            id.to_owned(),
            cost,
            behavior,
            base_surface_suffix.to_owned(),
            base_reading_suffix.to_owned(),
            forms,
        ));
    }
    assert_eq!(runtime_rows, 162, "expanded runtime row count changed");

    for (index, definition) in definitions.iter().enumerate() {
        let forms_name = format!("USER_POS_FORMS_{index}");
        writeln!(output, "static {forms_name}: &[UserPosForm] = &[").unwrap();
        for (form_id, form) in definition.5.iter().enumerate() {
            writeln!(
                output,
                "    UserPosForm {{ form_id: {form_id}, reading_suffix: {:?}, surface_suffix: {:?}, left_id: LeftContextId::new({}), right_id: RightContextId::new({}), left_pos: CoarsePos::{}, right_pos: CoarsePos::{} }},",
                form.reading_suffix,
                form.surface_suffix,
                form.context.id,
                form.context.id,
                form.context.coarse,
                form.context.coarse,
            )
            .unwrap();
        }
        writeln!(output, "];\n").unwrap();
    }

    writeln!(
        output,
        "pub static USER_POS_DEFINITIONS: &[UserPosDefinition] = &["
    )
    .unwrap();
    for (index, (id, cost, behavior, surface_base, reading_base, _)) in
        definitions.iter().enumerate()
    {
        writeln!(
            output,
            "    UserPosDefinition {{ id: {:?}, word_cost: {cost}, behavior: UserPosBehavior::{behavior}, base_reading_suffix: {:?}, base_surface_suffix: {:?}, forms: USER_POS_FORMS_{index} }},",
            id, reading_base, surface_base,
        )
        .unwrap();
    }
    writeln!(output, "];\n").unwrap();
    output
}

fn star_to_empty(value: &str) -> &str {
    if value == "*" { "" } else { value }
}

fn normalized_feature(feature: &str) -> String {
    let mut fields: Vec<&str> = feature.split(',').collect();
    assert!(fields.len() <= 7, "too many feature fields: {feature}");
    fields.resize(7, "*");
    fields.join(",")
}

fn resolve_context(contexts: &BTreeMap<String, Context>, pattern: &str) -> Option<Context> {
    if let Some(context) = contexts.get(pattern) {
        return Some(context.clone());
    }
    let pattern_fields: Vec<&str> = pattern.split(',').collect();
    contexts
        .iter()
        .filter(|(feature, _)| {
            feature
                .split(',')
                .zip(&pattern_fields)
                .all(|(actual, expected)| *expected == "*" || actual == *expected)
        })
        .map(|(_, context)| context)
        .min_by_key(|context| context.id)
        .cloned()
}
